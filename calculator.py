import math


def add(a, b):
    return a + b


def subtract(a, b):
    return a - b


def mul(a, b):
    return a * b


def div(a, b):
    return a / b


def logarithm(base, argument):
    return math.log(argument, base)


def hypotenuse(a, b):
    return math.hypot(a, b)


def square_root(a):
    return math.sqrt(a)


def exp(a, b):
    return a ** b
